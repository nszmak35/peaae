static int write_all(int fd, const char *p, size_t n)
{
    while (n > 0) {
        ssize_t w = write(fd, p, n);
        if (w < 0) {
            if (errno == EINTR || errno == EAGAIN)
                continue;
            return -1;
        }
        p += (size_t)w;
        n -= (size_t)w;
    }
    return 0;
}

struct buf {
    char *p;
    size_t n, cap;
    int failed;
};

static void buf_add(struct buf *b, const char *s, size_t n)
{
    if (b->failed)
        return;
    if (b->n + n + 1 > b->cap) {
        size_t ncap = b->cap ? b->cap : 4096;
        char *np;
        while (ncap < b->n + n + 1) {
            if (ncap > ((size_t)-1) / 2) {
                b->failed = 1;
                return;
            }
            ncap *= 2;
        }
        np = realloc(b->p, ncap);
        if (!np) {
            b->failed = 1;
            return;
        }
        b->p = np;
        b->cap = ncap;
    }
    memcpy(b->p + b->n, s, n);
    b->n += n;
    b->p[b->n] = '\0';
}

static void buf_str(struct buf *b, const char *s)
{
    buf_add(b, s, strlen(s));
}

static void buf_cup(struct buf *b, int row, int col)
{
    char tmp[48];
    int n = snprintf(tmp, sizeof tmp, "\x1b[%d;%dH", row, col);
    if (n > 0 && (size_t)n < sizeof tmp)
        buf_add(b, tmp, (size_t)n);
}

static double clampd(double v, double lo, double hi)
{
    if (!(v >= lo)) /* also catches NaN */
        return lo;
    return v > hi ? hi : v;
}

static int load_image(void)
{
    const size_t total = (size_t)IMG_W * IMG_H;
    const size_t stride = IMG_W + 1;
    uint8_t *px = calloc(total, 1);
    size_t pos = 0, i = 0;
    int color = 0;

    if (!px)
        return -1;

    while (i < sizeof img_rle) {
        uint64_t run = 0;
        int shift = 0;
        for (;;) {
            uint8_t b;
            if (i >= sizeof img_rle)
                goto bad;
            b = img_rle[i++];
            run |= (uint64_t)(b & 0x7f) << shift;
            if (!(b & 0x80))
                break;
            shift += 7;
            if (shift > 28)
                goto bad;
        }
        if (run > total - pos)
            goto bad;
        if (color)
            memset(px + pos, 1, (size_t)run);
        pos += (size_t)run;
        color ^= 1;
    }
    if (pos != total)
        goto bad;

    sat = calloc(stride * (IMG_H + 1), sizeof *sat);
    if (!sat)
        goto bad;
    for (int y = 0; y < IMG_H; y++) {
        for (int x = 0; x < IMG_W; x++) {
            sat[(size_t)(y + 1) * stride + (size_t)(x + 1)] =
                px[(size_t)y * IMG_W + (size_t)x]
                + sat[(size_t)y * stride + (size_t)(x + 1)]
                + sat[(size_t)(y + 1) * stride + (size_t)x]
                - sat[(size_t)y * stride + (size_t)x];
        }
    }
    free(px);
    return 0;

bad:
    free(px);
    free(sat);
    sat = NULL;
    return -1;
}

static double box_mean(double x0, double y0, double x1, double y1)
{
    const size_t stride = IMG_W + 1;
    int xi0, yi0, xi1, yi1;
    uint32_t s;

    x0 = clampd(x0, 0.0, IMG_W);
    x1 = clampd(x1, 0.0, IMG_W);
    y0 = clampd(y0, 0.0, IMG_H);
    y1 = clampd(y1, 0.0, IMG_H);

    xi0 = (int)floor(x0);
    yi0 = (int)floor(y0);
    xi1 = (int)ceil(x1);
    yi1 = (int)ceil(y1);
    if (xi1 < xi0 + 1) xi1 = xi0 + 1;
    if (yi1 < yi0 + 1) yi1 = yi0 + 1;
    if (xi1 > IMG_W) xi1 = IMG_W;
    if (yi1 > IMG_H) yi1 = IMG_H;
    if (xi0 > xi1 - 1) xi0 = xi1 - 1;
    if (yi0 > yi1 - 1) yi0 = yi1 - 1;

    s = sat[(size_t)yi1 * stride + (size_t)xi1]
      - sat[(size_t)yi0 * stride + (size_t)xi1]
      - sat[(size_t)yi1 * stride + (size_t)xi0]
      + sat[(size_t)yi0 * stride + (size_t)xi0];
    return (double)s / ((double)(xi1 - xi0) * (double)(yi1 - yi0));
}

static int fit_art(int term_rows, int term_cols, double aspect,
                   int *out_r, int *out_c)
{
    const double ar = aspect * (double)IMG_W / (double)IMG_H;
    int mx = 0, my = 0, avail_r, avail_c, r, c;

    if (term_rows >= 10 && term_cols >= 20) {
        mx = 2;
        my = 1;
    }
    avail_r = term_rows - 2 * my;
    avail_c = term_cols - 2 * mx;
    if (avail_r > MAX_ROWS) avail_r = MAX_ROWS;
    if (avail_c > MAX_COLS) avail_c = MAX_COLS;
    if (avail_r < 1 || avail_c < 1)
        return 0;

    r = avail_r;
    c = (int)(r * ar + 0.5);
    if (c > avail_c) {
        r = (int)(avail_c / ar);
        c = (int)(r * ar + 0.5);
        if (c > avail_c)
            c = avail_c;
    }
    if (r < 1 || c < 1)
        return 0;
    *out_r = r;
    *out_c = c;
    return 1;
}

static void render_grid(char *grid, int r, int c)
{
    const double cw = (double)IMG_W / c;
    const double ch = (double)IMG_H / r;
    const double zw = cw / ZONES_X;
    const double zh = ch / ZONES_Y;
    const double gain = GAIN * sqrt(zw * zh);

    for (int y = 0; y < r; y++) {
        for (int x = 0; x < c; x++) {
            float s[NZONES];
            float smax = 0.0f;
            int best = 0;
            float bestd = 1e30f;

            for (int zy = 0; zy < ZONES_Y; zy++) {
                for (int zx = 0; zx < ZONES_X; zx++) {
                    double x0 = x * cw + zx * zw - EXPAND * cw;
                    double x1 = x * cw + (zx + 1) * zw + EXPAND * cw;
                    double y0 = y * ch + zy * zh - EXPAND * ch;
                    double y1 = y * ch + (zy + 1) * zh + EXPAND * ch;
                    double v = box_mean(x0, y0, x1, y1) * gain;
                    float f = v > 1.0 ? 1.0f : (float)v;
                    s[zy * ZONES_X + zx] = f;
                    if (f > smax)
                        smax = f;
                }
            }

            if (smax < THRESH) {
                grid[(size_t)y * c + x] = ' ';
                continue;
            }
            for (int g = 0; g < NGLYPHS; g++) {
                float d = 0.0f;
                for (int k = 0; k < NZONES; k++) {
                    float diff = glyphs[g].z[k] / 255.0f - s[k];
                    d += diff * diff;
                }
                if (d < bestd) {
                    bestd = d;
                    best = g;
                }
            }
            grid[(size_t)y * c + x] = glyphs[best].ch;
        }
    }
}

static void get_term_size(int *rows, int *cols, double *aspect)
{
    struct winsize ws;
    int r = 0, c = 0;
    double a = DEFAULT_ASPECT;

    memset(&ws, 0, sizeof ws);
    if (ioctl(STDOUT_FILENO, TIOCGWINSZ, &ws) == 0 && ws.ws_row > 0 && ws.ws_col > 0) {
        r = ws.ws_row;
        c = ws.ws_col;
        if (ws.ws_xpixel > 0 && ws.ws_ypixel > 0) {
            double t = ((double)ws.ws_ypixel / ws.ws_row)
                     / ((double)ws.ws_xpixel / ws.ws_col);
            if (t >= 1.2 && t <= 3.5)
                a = t;
        }
    } else {
        const char *e;
        char *end;
        long v;
        if ((e = getenv("LINES")) != NULL) {
            v = strtol(e, &end, 10);
            if (end != e && v > 0 && v < 10000) r = (int)v;
        }
        if ((e = getenv("COLUMNS")) != NULL) {
            v = strtol(e, &end, 10);
            if (end != e && v > 0 && v < 10000) c = (int)v;
        }
        if (r <= 0) r = 24;
        if (c <= 0) c = 80;
    }
    *rows = r;
    *cols = c;
    *aspect = a;
}

static void restore_terminal(void)
{
    if (g_screen_active) {
        static const char seq[] = "\x1b[0m\x1b[?25h\x1b[?1049l";
        (void)write_all(STDOUT_FILENO, seq, sizeof seq - 1);
        g_screen_active = 0;
    }
    if (g_have_termios) {
        (void)tcsetattr(STDIN_FILENO, TCSAFLUSH, &g_orig_termios);
        g_have_termios = 0;
    }
}

static void on_signal(int sig)
{
    if (sig == SIGWINCH || sig == SIGCONT)
        g_resize = 1;
    else
        g_quit = 1;
}

static int draw_frame(int rows, int cols, double aspect, int color)
{
    struct buf b = { NULL, 0, 0, 0 };
    char *grid = NULL;
    int r, c, rc = 0;

    buf_str(&b, "\x1b[0m\x1b[2J");

    if (fit_art(rows, cols, aspect, &r, &c)) {
        grid = malloc((size_t)r * (size_t)c);
        if (grid) {
            int top = (rows - r) / 2;
            int left = (cols - c) / 2;

            render_grid(grid, r, c);
            if (color >= 0) {
                char tmp[32];
                int n = snprintf(tmp, sizeof tmp, "\x1b[38;5;%dm", color);
                if (n > 0 && (size_t)n < sizeof tmp)
                    buf_add(&b, tmp, (size_t)n);
            }
            for (int y = 0; y < r; y++) {
                const char *line = grid + (size_t)y * c;
                int first = 0, last = c - 1;
                while (first < c && line[first] == ' ') first++;
                if (first >= c)
                    continue;
                while (last > first && line[last] == ' ') last--;
                buf_cup(&b, top + y + 1, left + first + 1);
                buf_add(&b, line + first, (size_t)(last - first + 1));
            }
            buf_str(&b, "\x1b[0m");
        }
    }

    if (!b.failed && b.p)
        rc = write_all(STDOUT_FILENO, b.p, b.n);
    free(grid);
    free(b.p);
    return rc;
}

static double g_aspect_override = 0.0;   /* -a, 0 = auto-detect */

static int print_once(void)
{
    int rows, cols, r, c, left;
    double aspect;
    char *grid;
    struct buf b = { NULL, 0, 0, 0 };
    int rc = 0;

    get_term_size(&rows, &cols, &aspect);
    if (g_aspect_override > 0.0)
        aspect = g_aspect_override;
    if (!fit_art(rows, cols, aspect, &r, &c))
        return 0;

    grid = malloc((size_t)r * (size_t)c);
    if (!grid)
        return -1;
    render_grid(grid, r, c);
    left = (cols - c) / 2;

    for (int y = 0; y < r; y++) {
        const char *line = grid + (size_t)y * c;
        int last = c - 1;
        while (last >= 0 && line[last] == ' ')
            last--;
        if (last >= 0) {
            for (int i = 0; i < left; i++)
                buf_add(&b, " ", 1);
            buf_add(&b, line, (size_t)(last + 1));
        }
        buf_add(&b, "\n", 1);
    }
    if (b.failed || !b.p || write_all(STDOUT_FILENO, b.p, b.n) != 0)
        rc = -1;
    free(b.p);
    free(grid);
    return rc;
}

static int key_is_quit(const char *k, ssize_t n)
{
    if (n == 1 && k[0] == 27)
        return 1;
    for (ssize_t i = 0; i < n; i++) {
        if (k[i] == 'q' || k[i] == 'Q' || k[i] == 3 || k[i] == 4)
            return 1;
    }
    return 0;
}

static int run_tui(int color)
{
    static const int sigs[] = { SIGINT, SIGTERM, SIGHUP, SIGWINCH, SIGCONT };
    struct termios raw;
    struct sigaction sa;
    sigset_t block, old;
    int rows = 0, cols = 0, last_rows = -1, last_cols = -1;
    int redraw = 1, stdin_open = 1, rc = 0;
    double aspect = DEFAULT_ASPECT;

    if (tcgetattr(STDIN_FILENO, &g_orig_termios) != 0) {
        perror("peaae: tcgetattr");
        return 1;
    }
    g_have_termios = 1;
    atexit(restore_terminal);

    raw = g_orig_termios;
    raw.c_lflag &= (tcflag_t)~(ICANON | ECHO | ISIG | IEXTEN);
    raw.c_iflag &= (tcflag_t)~IXON;
    raw.c_cc[VMIN] = 1;
    raw.c_cc[VTIME] = 0;
    if (tcsetattr(STDIN_FILENO, TCSAFLUSH, &raw) != 0) {
        perror("peaae: tcsetattr");
        g_have_termios = 0;
        return 1;
    }

    memset(&sa, 0, sizeof sa);
    sa.sa_handler = on_signal;
    sigemptyset(&sa.sa_mask);
    sigemptyset(&block);
    for (size_t i = 0; i < sizeof sigs / sizeof sigs[0]; i++) {
        sigaction(sigs[i], &sa, NULL);
        sigaddset(&block, sigs[i]);
    }
    signal(SIGPIPE, SIG_IGN);
    sigprocmask(SIG_BLOCK, &block, &old);

    {
        static const char enter[] = "\x1b[?1049h\x1b[?25l";
        g_screen_active = 1;
        if (write_all(STDOUT_FILENO, enter, sizeof enter - 1) != 0)
            rc = 1;
    }

    while (!g_quit && rc == 0) {
        fd_set rf;
        struct timespec ts;
        int nfds = 0, n;

        get_term_size(&rows, &cols, &aspect);
        if (g_aspect_override > 0.0)
            aspect = g_aspect_override;

        if (g_resize || redraw || rows != last_rows || cols != last_cols) {
            g_resize = 0;
            redraw = 0;
            last_rows = rows;
            last_cols = cols;
            if (draw_frame(rows, cols, aspect, color) != 0) {
                rc = 1;
                break;
            }
        }

        FD_ZERO(&rf);
        if (stdin_open) {
            FD_SET(STDIN_FILENO, &rf);
            nfds = STDIN_FILENO + 1;
        }
        ts.tv_sec = 1;
        ts.tv_nsec = 0;
        n = pselect(nfds, &rf, NULL, NULL, &ts, &old);
        if (n < 0) {
            if (errno == EINTR)
                continue;
            rc = 1;
            break;
        }
        if (n > 0 && stdin_open && FD_ISSET(STDIN_FILENO, &rf)) {
            char kb[64];
            ssize_t k = read(STDIN_FILENO, kb, sizeof kb);
            if (k > 0) {
                if (key_is_quit(kb, k))
                    break;
            } else if (k == 0 || (errno != EINTR && errno != EAGAIN)) {
                stdin_open = 0;
            }
        }
    }

    restore_terminal();
    return rc;
}

static void usage(FILE *f)
{
    fputs("usage: peaae [-o] [-c COLOR] [-a ASPECT]\n"
          "       peaae -h | -V\n"
          "\n"
          "Shows ASCII art of Max Stirner in the middle of the terminal.\n"
          "It is redrawn when the terminal is resized; q or Esc quits.\n"
          "\n"
          "  -o         print the picture once and exit (plain text)\n"
          "  -c COLOR   draw with palette colour 0-255 instead of the\n"
          "             terminal's default foreground colour\n"
          "  -a ASPECT  cell height/width ratio, 1.0-4.0 (default: auto, 2.0)\n"
          "  -h         show this help\n"
          "  -V         show version\n", f);
}

int main(int argc, char **argv)
{
    int once = 0, color = -1, opt, rc;

    while ((opt = getopt(argc, argv, "hVoc:a:")) != -1) {
        char *end;
        switch (opt) {
        case 'h':
            usage(stdout);
            return 0;
        case 'V':
            puts("peaae " VERSION);
            return 0;
        case 'o':
            once = 1;
            break;
        case 'c': {
            long v = strtol(optarg, &end, 10);
            if (*optarg == '\0' || *end != '\0' || v < 0 || v > 255) {
                fprintf(stderr, "peaae: invalid colour '%s' (use 0-255)\n", optarg);
                return 2;
            }
            color = (int)v;
            break;
        }
        case 'a': {
            double v = strtod(optarg, &end);
            if (*optarg == '\0' || *end != '\0' || !(v >= 1.0 && v <= 4.0)) {
                fprintf(stderr, "peaae: invalid aspect '%s' (use 1.0-4.0)\n", optarg);
                return 2;
            }
            g_aspect_override = v;
            break;
        }
        default:
            usage(stderr);
            return 2;
        }
    }
    if (optind < argc) {
        usage(stderr);
        return 2;
    }

    if (load_image() != 0) {
        fprintf(stderr, "peaae: failed to decode the embedded picture\n");
        return 1;
    }

    if (once || !isatty(STDIN_FILENO) || !isatty(STDOUT_FILENO))
        rc = print_once() == 0 ? 0 : 1;
    else
        rc = run_tui(color);

    free(sat);
    return rc;
}
